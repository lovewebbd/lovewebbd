// Generate reverse dictionary for English -> Bangla
const bnTranslations = {};
for (let key in enTranslations) {
    bnTranslations[enTranslations[key]] = key;
}

function getAppLanguage() {
    let savedLang = localStorage.getItem('loveweb_lang');
    if (savedLang) return savedLang;
    
    // Auto-detect timezone for completely automatic global logic
    try {
        const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
        const newLang = (tz === 'Asia/Dhaka' || tz === 'Asia/Calcutta' || tz === 'Asia/Kolkata') ? 'bn' : 'en';
        localStorage.setItem('loveweb_lang', newLang);
        return newLang;
    } catch (e) {
        return 'bn'; 
    }
}

function setAppLanguage(lang) {
    localStorage.setItem('loveweb_lang', lang);
    applyLanguage(lang);
    updateLangToggleUI(lang);
}

function toggleAppLanguage() {
    const currentLang = getAppLanguage();
    const newLang = currentLang === 'en' ? 'bn' : 'en';
    setAppLanguage(newLang);
}

// Global available to inline clicks
window.setAppLanguage = setAppLanguage;
window.toggleAppLanguage = toggleAppLanguage;
window.getAppLanguage = getAppLanguage;
window.setAppLanguage = setAppLanguage;
window.enTranslations = enTranslations;

function applyLanguage(lang) {
    const dict = lang === 'en' ? enTranslations : bnTranslations;
    
    // Recursive translation function
    function translateNode(node) {
        if (node.nodeType === Node.TEXT_NODE) {
            let text = node.textContent.trim();
            if (text && dict[text]) {
                node.textContent = node.textContent.replace(text, dict[text]);
            }
        } else if (node.nodeType === Node.ELEMENT_NODE) {
            // Ignore scripts and styles
            if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE' || node.tagName === 'LINK' || node.tagName === 'META') return;
            
            // Translate placeholders
            if (node.placeholder && node.placeholder.trim()) {
                let p = node.placeholder.trim();
                if (dict[p]) {
                    node.placeholder = dict[p];
                }
            }
            
            // Translate input buttons
            if (node.tagName === 'INPUT' && (node.type === 'submit' || node.type === 'button') && node.value) {
                let val = node.value.trim();
                if (dict[val]) {
                    node.value = dict[val];
                }
            }
            
            // Recurse
            node.childNodes.forEach(translateNode);
        }
    }
    
    translateNode(document.body);
    
    // Also translate specific dynamic attributes if needed, but text content covers most.
}

function updateLangToggleUI(lang) {
    const isEn = lang === 'en';
    const drawerLangSwitch = document.getElementById('drawerLangSwitch');
    if (drawerLangSwitch) drawerLangSwitch.checked = isEn;
    const thumb = document.getElementById('drawerLangThumbText');
    if (thumb) thumb.innerText = isEn ? 'EN' : 'BN';
    const status = document.getElementById('drawerLangStatusText');
    if (status) status.innerText = isEn ? 'English' : 'বাংলা';

    const btnEn = document.getElementById('langBtnEn');
    const btnBn = document.getElementById('langBtnBn');
    const langBtnTexts = document.querySelectorAll('#langBtnText');
    
    langBtnTexts.forEach(langBtnText => {
        if (lang === 'en') {
            langBtnText.innerText = 'বাংলা';
        } else {
            langBtnText.innerText = 'ENG';
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    // Only apply if not on admin page
    if (window.location.pathname.includes('/admin')) return;
    
    const lang = getAppLanguage();
    // Use a slight delay to allow other dynamic content to render first
    setTimeout(() => {
        applyLanguage(lang);
        updateLangToggleUI(lang);
    }, 50);
    
    // Add mutation observer to translate dynamically added content (like modals, notifications)
    const observer = new MutationObserver((mutations) => {
        const currentLang = getAppLanguage();
        if (currentLang === 'en') { // We only need to dynamically translate to EN, BN is default HTML
            mutations.forEach(mutation => {
                mutation.addedNodes.forEach(node => {
                    if (node.nodeType === Node.ELEMENT_NODE || node.nodeType === Node.TEXT_NODE) {
                         applyLanguage(currentLang); // Brute force simple re-run on body is fast enough for small DOMs, but ideally we translate just the node.
                    }
                });
            });
        }
    });
    
    observer.observe(document.body, { childList: true, subtree: true });
});
